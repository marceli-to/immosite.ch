     The aspect ratio from the viewBox caps the mobile height at 45vh (docs/responsive-rules.md §7). --}}
@php
  $svg = file_get_contents(config('isometry.output'));
  preg_match('/viewBox="[-\d.]+ [-\d.]+ ([\d.]+) ([\d.]+)"/', $svg, $box);
  $ratio = isset($box[2]) && $box[2] > 0 ? round($box[1] / $box[2], 4) : 1;
@endphp

<div {{ $attributes->merge(['class' => 'mx-auto w-full max-w-[min(100%,calc(45vh*var(--iso-ratio)))] lg:max-w-none']) }}
  style="--iso-ratio: {{ $ratio }}; --iso-lift: {{ config('isometry.lift') }}">
  {!! $svg !!}
</div>
