<x-headings.h3 class="mt-32">Google Analytics</x-headings.h3>
<p>
  Diese Website nutzt Funktionen des Webanalysedienstes Google Analytics. Anbieter ist die Google LLC,
  1600 Amphitheatre Parkway, Mountain View, CA 94043, USA.
</p>
<p>
  Google Analytics verwendet so genannte «Cookies». Das sind Textdateien, die auf Ihrem Computer
  gespeichert werden und die eine Analyse der Benutzung der Website durch Sie ermöglichen. Die durch das
  Cookie erzeugten Informationen über Ihre Benutzung dieser Website werden in der Regel an einen Server von
  Google in den USA übertragen und dort gespeichert.
</p>
<p class="font-bold">IP-Anonymisierung</p>
<p>
  Wir haben auf dieser Website die Funktion IP-Anonymisierung aktiviert. Dadurch wird Ihre IP-Adresse von
  Google innerhalb von Mitgliedstaaten der Europäischen Union oder in anderen Vertragsstaaten des Abkommens
  über den Europäischen Wirtschaftsraum vor der Übermittlung in die USA gekürzt. Nur in Ausnahmefällen wird
  die volle IP-Adresse an einen Server von Google in den USA übertragen und dort gekürzt. Im Auftrag des
  Betreibers dieser Website wird Google diese Informationen benutzen, um Ihre Nutzung der Website
  auszuwerten, um Reports über die Websiteaktivitäten zusammenzustellen und um weitere mit der
  Websitenutzung und der Internetnutzung verbundene Dienstleistungen gegenüber dem Websitebetreiber zu
  erbringen. Die im Rahmen von Google Analytics von Ihrem Browser übermittelte IP-Adresse wird nicht mit
  anderen Daten von Google zusammengeführt.
</p>
<p class="font-bold">Browser Plugin</p>
<p>
  Sie können die Speicherung der Cookies durch eine entsprechende Einstellung Ihrer Browser-Software
  verhindern; wir weisen Sie jedoch darauf hin, dass Sie in diesem Fall gegebenenfalls nicht sämtliche
  Funktionen dieser Website vollumfänglich werden nutzen können. Sie können darüber hinaus die Erfassung der
  durch das Cookie erzeugten und auf Ihre Nutzung der Website bezogenen Daten (inkl. Ihrer IP-Adresse) an
  Google sowie die Verarbeitung dieser Daten durch Google verhindern, indem Sie das unter diesem
  <a href="https://tools.google.com/dlpage/gaoptout?hl=de" target="_blank" rel="noopener noreferrer">Link</a>
  verfügbare Browser-Plugin herunterladen und installieren.
</p>
<p>
  Mehr Informationen zum Umgang mit Nutzerdaten bei Google Analytics finden Sie in der
  <a href="https://support.google.com/analytics/answer/6004245?hl=de" target="_blank" rel="noopener noreferrer">Datenschutzerklärung von Google</a>.
</p>
