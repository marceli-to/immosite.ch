<x-headings.h3 class="mt-32">Verwendung von Adobe Fonts</x-headings.h3>
<p>
  Wir verwenden auf dieser Webseite die Schriftarten von Adobe Fonts, um ein ansprechendes Design und eine
  bessere Lesbarkeit zu gewährleisten. Adobe Fonts ist ein Dienst der Adobe Systems Software Ireland
  Limited, 4-6 Riverwalk, Citywest Business Campus, Dublin 24, Irland.
</p>
<p>
  Beim Besuch dieser Webseite werden die Schriften von Adobe von Ihrem Browser geladen, um die Schrift
  korrekt darzustellen. Zu diesen Informationen können auch personenbezogene Daten gehören, insbesondere:
</p>
<ul>
  <li>IP-Adresse des Geräts, von dem aus auf die Webseite zugegriffen wird</li>
  <li>Datum und Uhrzeit des Zugriffs</li>
  <li>Browsertyp und -version</li>
  <li>Betriebssystem des Geräts</li>
  <li>Spracheinstellungen des Browsers</li>
</ul>
<p>
  Die Verarbeitung Ihrer personenbezogenen Daten im Zusammenhang mit Adobe Fonts erfolgt zum Zweck der
  Darstellung der Schriftarten auf dieser Webseite und zur Gewährleistung einer einheitlichen und
  ansprechenden visuellen Gestaltung.
</p>
<p>
  Weitere Informationen zur Datenverarbeitung durch Adobe Fonts finden Sie in der
  <a href="https://www.adobe.com/de/privacy/policies/adobe-fonts.html" target="_blank" rel="noopener noreferrer">Datenschutzerklärung von Adobe Fonts</a>.
</p>
